export function buildTemplateWorkbook(): { buffer: ArrayBuffer; filename: string } {
  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.aoa_to_sheet([HEADERS, ...ROWS]);
  ws["!cols"] = HEADERS.map((_, i) => ({ wch: i === 2 ? 40 : i === 10 ? 30 : 12 }));
  XLSX.utils.book_append_sheet(wb, ws, "题库模板");
  const guide = XLSX.utils.aoa_to_sheet(GUIDE);
  guide["!cols"] = [{ wch: 90 }];
  XLSX.utils.book_append_sheet(wb, guide, "填写说明");
  const out = XLSX.write(wb, { bookType: "xlsx", type: "array" });
  return { buffer: out as ArrayBuffer, filename: "小驴考试-题库导入模板.xlsx" };
}
